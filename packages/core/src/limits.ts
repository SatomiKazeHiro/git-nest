/**
 * 批量上限。**只有这一份**，前后端都从这里读。
 *
 * 为什么把它放进 core（而不是留在 server 的路由里）：上限原来是五个各写各的数字
 * （`GET /api/status` 200、check 200、apply 200、import 200、扫描 500），而**前端
 * 一个都不知道**。后果很实在：项目超过 200 个时，列表页把全部 id 一次发出去 →
 * 400 → 而前端把那个错误丢掉了 → 每一行永远显示「读状态…」；点「联网检查更新」
 * 则拿到一句 422「参数有误」，用户根本看不出是数量问题。
 *
 * 所以规则是：**服务端按它校验，前端按它分块或提前拦下**，两边读同一个数字。
 * 改这里就等于同时改了前后端——这正是要的效果（以前改一处、另一处不知道）。
 */

/** `GET /api/status?ids=` 一次最多查几个。**前端会自动分块**，用户不需要知道这个数。 */
export const MAX_STATUS_IDS = 200

/**
 * 一次批量检查 / 更新最多几个仓库。
 *
 * 给得比 status 大：check / apply 是**后台任务 + SSE 进度 + 确认阈值**，本来就为
 * 「一次处理很多个」设计的（每个仓库约 10 条 git 命令，按并发上限 4 摊）。
 * 它只是一个「别把整个清单误当成一次点击」的护栏，不是能力上限。
 */
export const MAX_BATCH_IDS = 1000

/**
 * 一次扫描最多列出多少仓库，同时也是一次导入最多接受多少条路径。
 *
 * **两个数字必须是同一个**：扫描是「列出候选」、导入是「把选中的加进清单」，
 * 如果扫描能列出 500 而导入只收 200，用户就会在「全选 → 添加」这一步撞墙。
 * 现在扫描的结果集永远不会超过导入能吃的量，这是构造上成立的，不靠人去对。
 */
export const MAX_SCAN_RESULTS = 500
