/**
 * 点某一行要去哪儿。
 *
 * **再点当前这一行 = 反选**（用户原话：打开右侧详情之后没法主动关掉它）。
 * `/` 与 `/projects/:id` 渲染的是同一个界面，区别只在清单下面那一轨有没有内容——
 * 所以「关掉详情」在这套路由里就是「回到 `/`」：不需要另立一个 `detailOpen` 状态，
 * 也不需要记住上次看的是谁（地址栏里就是它），浏览器前进后退照旧说得通。
 *
 * 抽成纯函数是因为它有两个调用点（行的链接、行的点击），而这条判定只能有一份：
 * 两处各写一遍 `currentId === id ? '/' : …`，改一处漏一处不会报错，
 * 症状是「点名字能关、点行的空白处关不掉」这种只有用户会碰到的怪事。
 */
export function detailPath(currentId: number | null, id: number): string {
  return currentId === id ? '/' : `/projects/${id}`
}
